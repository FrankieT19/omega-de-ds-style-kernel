#!/usr/bin/env python3
"""Generate a tiny public-domain (CC0) PC Engine test ROM: inits VDC/VCE, then loops
writing a counter into palette entries 0 and 0x100 -> animated colour stripes.
Written for this project; no third-party code."""
import sys
L = 0xE000
code = bytes([0x78,0xD4,0xD8,0xA2,0xFF,0x9A,      # sei csh cld ldx#ff txs
  0xA9,0xFF,0x53,0x01, 0xA9,0xF8,0x53,0x02,          # MPR0=$FF(io) MPR1=$F8(ram)
  0xA9,0x07,0x8D,0x02,0x14, 0x9C,0x00,0x04])          # irq off, VCE ctrl=0
for r,v in [(0x09,0),(0x0A,0x0202),(0x0B,0x031F),(0x0C,0x0F02),(0x0D,0x00EF),(0x0E,3),(0x05,0x0080)]:
    code += bytes([0x03,r,0x13,v&0xFF,0x23,v>>8])     # st0/st1/st2
code += bytes([0xA2,0,0xA0,0])
loop = L + len(code)
code += bytes([0xE8,0xD0,0x01,0xC8, 0x9C,0x02,0x04,0x9C,0x03,0x04,0x8E,0x04,0x04,0x8C,0x05,0x04,
               0x9C,0x02,0x04,0xA9,0x01,0x8D,0x03,0x04,0x8E,0x04,0x04,0x8C,0x05,0x04,
               0x4C,loop&0xFF,loop>>8])
rti = L + len(code); code += b'\x40'
bank = bytearray(b'\xFF'*0x2000); bank[:len(code)] = code
for off in range(0x1FF6, 0x2000, 2):                   # all vectors -> rti, reset -> start
    bank[off:off+2] = rti.to_bytes(2,'little')
bank[0x1FFE:0x2000] = L.to_bytes(2,'little')
open(sys.argv[1] if len(sys.argv)>1 else 'pcetest.pce','wb').write(bytes(bank)*4)  # 32 KB
