/* thai620.h - Thai TIS-620 bitmap font (8x12, 91 glyphs)
 * 
 * Created by aidia_dayo on 18/6/2569 BE.
 *
 * TIS-620 byte range 0xA1-0xFB, maps to Unicode U+0E01-U+0E5B.
 * Each glyph is 8 cols x 12 rows, bit7 = leftmost pixel.
 * Cluster rendering logic is in thai_cluster.h.
 *
 * Glyph rows (0-indexed):
 *   0-3  = above zone (tones, above vowels)
 *   4-9  = consonant body
 *   10-11 = below vowels
 *
 * Note: when a tonal mark sits above a sara (e.g. ข้า ก้า), the renderer
 * shifts the tone up by 1 row (yoff = -1), so rendering can reach y-1.
 * Effective cell height is 13px, not 12. If you do partial row clears
 * (scroll, highlight changes), use THAI_CLEAR_Y/THAI_CLEAR_H to widen
 * the clear region by 1 when Thai is active, or you get a ghost pixel.
 *
 * Sara am (ำ) is split: THAI_DATA[50] is just the head circle. The า tail
 * is drawn separately after the cluster advance. See thai_cluster.h.
 */

